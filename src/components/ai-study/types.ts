export type Phase = "upload" | "processing" | "results";

export interface AIQuestion {
  id: string;
  question: string;
  options: string[];
  correctIndex: number;
  explanation: string;
}

export interface AINote {
  keyConcepts: string[];
  definitions: Array<{ term: string; definition: string }>;
  summary: string;
  studyTips: string[];
}

/** Whether the subject was inferred from real file content, the filename, corrected by the student, or matched from a library book. */
export type DetectionSource = "content" | "filename" | "manual" | "library";

export interface AIResult {
  subject: string;
  filename: string;
  questions: AIQuestion[];
  notes: AINote;
  /** Short snippet of the text we actually extracted from the file, if any. */
  excerpt: string;
  detectionSource: DetectionSource;
  /** Whether this pack was actually generated by the configured AI provider, or
   * came from the built-in demo question bank (no AI configured, or the API
   * call failed). Always show this honestly to the student — never let a demo
   * pack look like it was generated from their file. */
  source: "ai" | "demo";
}
