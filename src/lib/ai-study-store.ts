/**
 * Per-student log of AI Study packs they've generated — pure UX convenience
 * (quick "practice again" + score recall), never wired to XP/wallet. Mirrors
 * the per-user localStorage pattern used by favorites-store.ts and
 * reading-position-store.ts.
 */
const STORAGE_KEY = "study2earn-ai-study-history";
const MAX_ENTRIES_PER_USER = 8;

export type AiDetectionSource = "content" | "filename" | "manual" | "library";

export interface AiStudyHistoryEntry {
  id: string;
  subject: string;
  filename: string;
  questionCount: number;
  detectionSource: AiDetectionSource;
  createdAt: string;
  answeredCount?: number;
  correctCount?: number;
  scorePct?: number;
  /** Whether this pack was generated by the configured AI provider or the
   * built-in demo bank. Optional — older entries predate this field and are
   * treated as "demo" by callers, since AI generation didn't exist before it. */
  source?: "ai" | "demo";
}

type HistoryStore = Record<string, AiStudyHistoryEntry[]>;

function readStore(): HistoryStore {
  if (typeof window === "undefined") return {};
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    return raw ? (JSON.parse(raw) as HistoryStore) : {};
  } catch {
    return {};
  }
}

function writeStore(store: HistoryStore) {
  if (typeof window === "undefined") return;
  localStorage.setItem(STORAGE_KEY, JSON.stringify(store));
  window.dispatchEvent(new Event("ai-study-history-change"));
}

export function subscribeAiStudyHistory(cb: () => void) {
  window.addEventListener("ai-study-history-change", cb);
  return () => window.removeEventListener("ai-study-history-change", cb);
}

export function getAiStudyHistory(userId: string): AiStudyHistoryEntry[] {
  if (!userId) return [];
  return readStore()[userId] ?? [];
}

export function addAiStudyHistoryEntry(
  userId: string,
  entry: Omit<AiStudyHistoryEntry, "id" | "createdAt">,
): string | null {
  if (!userId) return null;
  const store = readStore();
  const id = `${Date.now().toString(36)}${Math.random().toString(36).slice(2, 8)}`;
  const record: AiStudyHistoryEntry = { ...entry, id, createdAt: new Date().toISOString() };
  const mine = [record, ...(store[userId] ?? [])].slice(0, MAX_ENTRIES_PER_USER);
  store[userId] = mine;
  writeStore(store);
  return id;
}

export function updateAiStudyHistoryScore(
  userId: string,
  id: string,
  score: { answeredCount: number; correctCount: number; scorePct: number },
) {
  if (!userId || !id) return;
  const store = readStore();
  const mine = store[userId] ?? [];
  const idx = mine.findIndex((e) => e.id === id);
  if (idx === -1) return;
  mine[idx] = { ...mine[idx], ...score };
  store[userId] = [...mine];
  writeStore(store);
}

export function removeAiStudyHistoryEntry(userId: string, id: string) {
  if (!userId) return;
  const store = readStore();
  store[userId] = (store[userId] ?? []).filter((e) => e.id !== id);
  writeStore(store);
}

export function clearAiStudyHistory(userId: string) {
  if (!userId) return;
  const store = readStore();
  store[userId] = [];
  writeStore(store);
}
